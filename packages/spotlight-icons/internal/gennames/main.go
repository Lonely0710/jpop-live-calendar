// Command gennames generates names_gen.go from icons.json and svg/.
// Run it with `go generate ./...` from the module root.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

type entry struct {
	Name  string `json:"name"`
	Group string `json:"group"`
}

func ident(name string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(name, func(r rune) bool { return r == '-' || r == '_' || r == ' ' }) {
		switch part {
		case "api", "rss":
			b.WriteString(strings.ToUpper(part))
		default:
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

func main() {
	raw, err := os.ReadFile("icons.json")
	if err != nil {
		log.Fatal(err)
	}
	var entries []entry
	if err := json.Unmarshal(raw, &entries); err != nil {
		log.Fatal(err)
	}
	for _, e := range entries {
		if _, err := os.Stat(filepath.Join("svg", e.Name+".svg")); err != nil {
			log.Fatalf("icons.json lists %q but svg/%s.svg is missing", e.Name, e.Name)
		}
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/gennames; DO NOT EDIT.\n\npackage spotlighticons\n\n")
	buf.WriteString("// Icon names.\nconst (\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t%s Name = %q\n", ident(e.Name), e.Name)
	}
	buf.WriteString(")\n\n// All lists every icon in library order.\nvar All = []Name{\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t%s,\n", ident(e.Name))
	}
	buf.WriteString("}\n\nvar groups = map[Name]Group{\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t%s: %q,\n", ident(e.Name), e.Group)
	}
	buf.WriteString("}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("names_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
